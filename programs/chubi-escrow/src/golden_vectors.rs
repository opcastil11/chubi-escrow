//! Golden vectors — the contract's money math, serialized for other languages.
//!
//! The frontend re-implements `compute_entry_weight`, `compute_twcd`,
//! `compute_winner_payout`, `compute_loser_payout` and
//! `compute_withdrawal_penalty` in JavaScript so it can show a payout preview
//! before the user signs. Nothing structural stops those two implementations
//! from drifting apart, and when they do the user sees a number the chain will
//! not honour.
//!
//! `cargo test` writes this file's output to `golden-vectors.json` at the repo
//! root. Copy it into the app repo and the JS mirror is checked against the
//! real thing:
//!
//! ```text
//! cd chubi-escrow && cargo test
//! cp golden-vectors.json \
//!    ../chubi/conviction-market-protocol/frontend/src/utils/__fixtures__/golden-vectors.json
//! ```
//!
//! Regenerate and re-copy whenever `math.rs` changes. The JS test fails loudly
//! if the fixture and the mirror disagree.

#![cfg(test)]

use crate::constants::*;
use crate::math::*;

/// Empty pools array, for building fixtures side by side.
fn pools(vals: &[u64]) -> [u64; MAX_SIDES] {
    let mut p = [0u64; MAX_SIDES];
    for (i, v) in vals.iter().enumerate() {
        p[i] = *v;
    }
    p
}

fn weighted(vals: &[u128]) -> [u128; MAX_SIDES] {
    let mut p = [0u128; MAX_SIDES];
    for (i, v) in vals.iter().enumerate() {
        p[i] = *v;
    }
    p
}

fn arr_u64(a: &[u64; MAX_SIDES]) -> String {
    a.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(",")
}

fn arr_u128(a: &[u128; MAX_SIDES]) -> String {
    a.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(",")
}

#[test]
fn emit_golden_vectors() {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str("  \"_readme\": \"Generated by `cargo test emit_golden_vectors` in chubi-escrow. Do not edit by hand.\",\n");
    out.push_str(&format!(
        "  \"constants\": {{ \"PRECISION\": {}, \"MIN_WEIGHT_FLOOR\": {}, \"PROTOCOL_FEE_BPS\": {}, \"CREATOR_FEE_BPS\": {}, \"BPS_SCALE\": {}, \"MIN_TRANSFER_BPS\": {}, \"SHORT_DURATION_SECS\": {} }},\n",
        PRECISION, MIN_WEIGHT_FLOOR, PROTOCOL_FEE_BPS, CREATOR_FEE_BPS, BPS_SCALE, MIN_TRANSFER_BPS, SHORT_DURATION_SECS
    ));

    // ── compute_entry_weight ────────────────────────────────────────────────
    // Boundaries (0, PRECISION, above PRECISION), both exponent branches, and
    // the 30-minute cutoff from either side.
    let weight_cases: &[(u64, i64)] = &[
        (PRECISION, 86_400),   // full time remaining
        (0, 86_400),           // no time remaining → floor
        (2_000_000, 86_400),   // above PRECISION → clamped
        (500_000, 600),        // 10-min market, linear branch
        (500_000, 1_799),      // just under the 30-min cutoff → still linear
        (500_000, 1_800),      // exactly at the cutoff → quadratic
        (500_000, 7_200),      // 2h
        (500_000, 604_800),    // 7d — same curve (cubic branch was removed)
        (250_000, 3_600),
        (750_000, 3_600),
        (900_000, 600),
        (1, 86_400),           // near-zero fraction, quadratic → rounds to floor
        (999_999, 600),
    ];
    out.push_str("  \"entry_weight\": [\n");
    for (i, (frac, dur)) in weight_cases.iter().enumerate() {
        let w = compute_entry_weight(*frac, *dur).unwrap();
        out.push_str(&format!(
            "    {{ \"fraction_remaining\": {}, \"resolution_duration\": {}, \"weight\": {} }}{}\n",
            frac, dur, w, if i + 1 < weight_cases.len() { "," } else { "" }
        ));
    }
    out.push_str("  ],\n");

    // ── compute_twcd ────────────────────────────────────────────────────────
    // (winner, twd_0, pools, num_sides)
    let twcd_cases: Vec<(u8, u64, [u64; MAX_SIDES], u8)> = vec![
        // Perfectly balanced, TWD matches the final split → no swing.
        (0, 500_000, pools(&[50_000_000_000, 50_000_000_000]), 2),
        // Winner led all along → small swing.
        (0, 800_000, pools(&[80_000_000_000, 20_000_000_000]), 2),
        // Late flip: TWD says B dominated, A wins on the final pool.
        (0, 300_000, pools(&[80_000_000_000, 20_000_000_000]), 2),
        // Same flip from B's perspective.
        (1, 700_000, pools(&[20_000_000_000, 80_000_000_000]), 2),
        // Safety-floor case: wps computes below the winner's own pool share,
        // which would hand winners less than they put in. Floor kicks in.
        (0, 500_000, pools(&[90_000_000_000, 10_000_000_000]), 2),
        // Extreme swing → dominance clamps at 0, wps = 50% before the floor.
        (0, 100_000, pools(&[90_000_000_000, 10_000_000_000]), 2),
        // Empty market.
        (0, 500_000, pools(&[0, 0]), 2),
        // Multi-option → winner takes all, TWD ignored.
        (1, 300_000, pools(&[10_000_000_000, 20_000_000_000, 30_000_000_000]), 3),
        // Lopsided but consistent.
        (0, 990_000, pools(&[99_000_000_000, 1_000_000_000]), 2),
    ];
    out.push_str("  \"twcd\": [\n");
    for (i, (winner, twd_0, p, n)) in twcd_cases.iter().enumerate() {
        let wps = compute_twcd(*winner, *twd_0, p, *n).unwrap();
        out.push_str(&format!(
            "    {{ \"winner\": {}, \"twd_0\": {}, \"pools\": [{}], \"num_sides\": {}, \"winner_payout_share\": {} }}{}\n",
            winner, twd_0, arr_u64(p), n, wps, if i + 1 < twcd_cases.len() { "," } else { "" }
        ));
    }
    out.push_str("  ],\n");

    // ── compute_winner_payout ───────────────────────────────────────────────
    // (amount, entry_weight, winner_side, pools, weighted_pools,
    //  winner_payout_share, total_distributable, creator_fee_bps)
    struct WinCase {
        label: &'static str,
        amount: u64,
        entry_weight: u64,
        winner_side: u8,
        pools: [u64; MAX_SIDES],
        weighted: [u128; MAX_SIDES],
        wps: u64,
        total_distributable: u64,
        creator_fee_bps: u64,
    }
    let win_cases = vec![
        WinCase {
            label: "typical winner, 2% protocol fee only",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            winner_side: 0,
            pools: pools(&[10_000_000_000, 10_000_000_000]),
            weighted: weighted(&[10_000_000_000_000_000, 8_000_000_000_000_000]),
            wps: 750_000,
            total_distributable: 20_000_000_000,
            creator_fee_bps: 0,
        },
        WinCase {
            label: "same, with the 0.5% creator fee",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            winner_side: 0,
            pools: pools(&[10_000_000_000, 10_000_000_000]),
            weighted: weighted(&[10_000_000_000_000_000, 8_000_000_000_000_000]),
            wps: 750_000,
            total_distributable: 20_000_000_000,
            creator_fee_bps: CREATOR_FEE_BPS,
        },
        WinCase {
            label: "late entry, floor weight",
            amount: 500_000_000,
            entry_weight: MIN_WEIGHT_FLOOR,
            winner_side: 1,
            pools: pools(&[30_000_000_000, 12_000_000_000]),
            weighted: weighted(&[25_000_000_000_000_000, 9_000_000_000_000_000]),
            wps: 620_000,
            total_distributable: 42_000_000_000,
            creator_fee_bps: CREATOR_FEE_BPS,
        },
        WinCase {
            // winner_pool < winner_investment: profit_pool is 0 and the
            // contract SCALES THE PRINCIPAL DOWN. A mirror that returns the
            // full principal here promises money the chain will not pay.
            label: "underwater winner pool — principal is scaled down, not returned whole",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            winner_side: 0,
            pools: pools(&[18_000_000_000, 2_000_000_000]),
            weighted: weighted(&[18_000_000_000_000_000, 2_000_000_000_000_000]),
            wps: 510_000,
            total_distributable: 20_000_000_000,
            creator_fee_bps: 0,
        },
        WinCase {
            // Exactly break-even: winner_pool == winner_investment.
            label: "break-even winner pool",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            winner_side: 0,
            pools: pools(&[10_000_000_000, 10_000_000_000]),
            weighted: weighted(&[10_000_000_000_000_000, 10_000_000_000_000_000]),
            wps: 500_000,
            total_distributable: 20_000_000_000,
            creator_fee_bps: 0,
        },
        WinCase {
            label: "no weighted pool on the winning side → zero payout",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            winner_side: 0,
            pools: pools(&[0, 10_000_000_000]),
            weighted: weighted(&[0, 10_000_000_000_000_000]),
            wps: 750_000,
            total_distributable: 10_000_000_000,
            creator_fee_bps: 0,
        },
        WinCase {
            // total_distributable includes market.penalty_pool, which is why a
            // mirror that passes only sum(pools) under-quotes withdrawal markets.
            label: "penalty pool folded into total_distributable",
            amount: 1_000_000_000,
            entry_weight: 900_000,
            winner_side: 0,
            pools: pools(&[10_000_000_000, 10_000_000_000]),
            weighted: weighted(&[9_000_000_000_000_000, 8_000_000_000_000_000]),
            wps: 750_000,
            total_distributable: 23_500_000_000, // 20 SOL pools + 3.5 SOL penalties
            creator_fee_bps: CREATOR_FEE_BPS,
        },
        WinCase {
            label: "dust deposit",
            amount: MIN_DEPOSIT_LAMPORTS,
            entry_weight: 475_000,
            winner_side: 0,
            pools: pools(&[5_000_000_000, 5_000_000_000]),
            weighted: weighted(&[4_000_000_000_000_000, 4_000_000_000_000_000]),
            wps: 800_000,
            total_distributable: 10_000_000_000,
            creator_fee_bps: 0,
        },
    ];
    out.push_str("  \"winner_payout\": [\n");
    for (i, c) in win_cases.iter().enumerate() {
        let (payout, fee, creator_fee) = compute_winner_payout(
            c.amount, c.entry_weight, c.winner_side, &c.pools, &c.weighted,
            c.wps, c.total_distributable, c.creator_fee_bps,
        ).unwrap();
        out.push_str(&format!(
            "    {{ \"label\": \"{}\", \"amount\": {}, \"entry_weight\": {}, \"winner_side\": {}, \"pools\": [{}], \"weighted_pools\": [{}], \"winner_payout_share\": {}, \"total_distributable\": {}, \"creator_fee_bps\": {}, \"payout\": {}, \"fee\": {}, \"creator_fee\": {} }}{}\n",
            c.label, c.amount, c.entry_weight, c.winner_side, arr_u64(&c.pools),
            arr_u128(&c.weighted), c.wps, c.total_distributable, c.creator_fee_bps,
            payout, fee, creator_fee,
            if i + 1 < win_cases.len() { "," } else { "" }
        ));
    }
    out.push_str("  ],\n");

    // ── compute_loser_payout ────────────────────────────────────────────────
    struct LoseCase {
        label: &'static str,
        amount: u64,
        entry_weight: u64,
        loser_side: u8,
        weighted: [u128; MAX_SIDES],
        wps: u64,
        total_distributable: u64,
    }
    let lose_cases = vec![
        LoseCase {
            label: "typical loser, partial refund",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            loser_side: 1,
            weighted: weighted(&[10_000_000_000_000_000, 8_000_000_000_000_000]),
            wps: 750_000,
            total_distributable: 20_000_000_000,
        },
        LoseCase {
            // Consolation share exceeds the stake — the cap must bite, or a
            // "losing" position would turn a profit.
            label: "capped at principal — losers never profit",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            loser_side: 1,
            weighted: weighted(&[10_000_000_000_000_000, 1_000_000_000_000_000]),
            wps: 500_000,
            total_distributable: 40_000_000_000,
        },
        LoseCase {
            label: "no weighted pool on the losing side",
            amount: 1_000_000_000,
            entry_weight: 1_000_000,
            loser_side: 1,
            weighted: weighted(&[10_000_000_000_000_000, 0]),
            wps: 750_000,
            total_distributable: 20_000_000_000,
        },
        LoseCase {
            label: "winner takes all → loser gets nothing",
            amount: 2_000_000_000,
            entry_weight: 600_000,
            loser_side: 0,
            weighted: weighted(&[5_000_000_000_000_000, 5_000_000_000_000_000]),
            wps: PRECISION,
            total_distributable: 10_000_000_000,
        },
        LoseCase {
            label: "floor-weight loser in a deep pool",
            amount: 750_000_000,
            entry_weight: MIN_WEIGHT_FLOOR,
            loser_side: 0,
            weighted: weighted(&[40_000_000_000_000_000, 60_000_000_000_000_000]),
            wps: 680_000,
            total_distributable: 105_000_000_000,
        },
    ];
    out.push_str("  \"loser_payout\": [\n");
    for (i, c) in lose_cases.iter().enumerate() {
        let payout = compute_loser_payout(
            c.amount, c.entry_weight, c.loser_side, &c.weighted, c.wps, c.total_distributable,
        ).unwrap();
        out.push_str(&format!(
            "    {{ \"label\": \"{}\", \"amount\": {}, \"entry_weight\": {}, \"loser_side\": {}, \"weighted_pools\": [{}], \"winner_payout_share\": {}, \"total_distributable\": {}, \"payout\": {} }}{}\n",
            c.label, c.amount, c.entry_weight, c.loser_side, arr_u128(&c.weighted),
            c.wps, c.total_distributable, payout,
            if i + 1 < lose_cases.len() { "," } else { "" }
        ));
    }
    out.push_str("  ],\n");

    // ── compute_withdrawal_penalty ──────────────────────────────────────────
    // Every tier plus both sides of every boundary.
    let pen_cases: &[(i64, i64)] = &[
        (0, 1_000), (99, 1_000), (100, 1_000), (299, 1_000), (300, 1_000),
        (499, 1_000), (500, 1_000), (749, 1_000), (750, 1_000), (1_000, 1_000),
        (2_000, 1_000), (10, 0), (43_200, 86_400),
    ];
    out.push_str("  \"withdrawal_penalty\": [\n");
    for (i, (elapsed, duration)) in pen_cases.iter().enumerate() {
        let bps = compute_withdrawal_penalty(*elapsed, *duration);
        out.push_str(&format!(
            "    {{ \"elapsed\": {}, \"duration\": {}, \"penalty_bps\": {} }}{}\n",
            elapsed, duration, bps, if i + 1 < pen_cases.len() { "," } else { "" }
        ));
    }
    out.push_str("  ]\n}\n");

    let path = std::env::var("CHUBI_GOLDEN_OUT").unwrap_or_else(|_| {
        format!("{}/../../golden-vectors.json", env!("CARGO_MANIFEST_DIR"))
    });
    std::fs::write(&path, &out).unwrap_or_else(|e| panic!("write {}: {}", path, e));

    // Sanity: the file we just wrote is the shape the JS test expects.
    assert!(out.contains("\"entry_weight\""));
    assert!(out.contains("\"winner_payout\""));
    assert!(out.len() > 1_000);
}

/// The one behaviour a float mirror is most likely to get wrong, pinned as a
/// normal assertion so it fails even if nobody regenerates the fixture:
/// when the winning side's share of the pot is smaller than what that side put
/// in, the contract does NOT return the principal — it scales it down.
#[test]
fn underwater_winner_loses_principal() {
    let p = pools(&[18_000_000_000, 2_000_000_000]);
    let w = weighted(&[18_000_000_000_000_000, 2_000_000_000_000_000]);
    let (payout, fee, creator_fee) =
        compute_winner_payout(1_000_000_000, 1_000_000, 0, &p, &w, 510_000, 20_000_000_000, 0).unwrap();
    // winner_pool = 20 SOL * 0.51 = 10.2 SOL, but side 0 deposited 18 SOL.
    // payout = 10.2/18 of the stake.
    assert!(payout < 1_000_000_000, "underwater winner must not get principal back");
    assert_eq!(payout, 566_666_666);
    assert_eq!(fee, 0);
    assert_eq!(creator_fee, 0);
}

/// `total_distributable` is `sum(pools) + penalty_pool`. Dropping the penalty
/// pool silently under-quotes every market that allows withdrawal.
#[test]
fn penalty_pool_raises_the_payout() {
    let p = pools(&[10_000_000_000, 10_000_000_000]);
    let w = weighted(&[10_000_000_000_000_000, 8_000_000_000_000_000]);
    let (without, _, _) =
        compute_winner_payout(1_000_000_000, 1_000_000, 0, &p, &w, 750_000, 20_000_000_000, 0).unwrap();
    let (with, _, _) =
        compute_winner_payout(1_000_000_000, 1_000_000, 0, &p, &w, 750_000, 23_500_000_000, 0).unwrap();
    assert!(with > without);
}
